'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('bd', {
  defaultDir: () => ipcRenderer.invoke('default-dir'),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  start: (opts) => ipcRenderer.invoke('start', opts),
  cancel: () => ipcRenderer.invoke('cancel'),
  reveal: (p) => ipcRenderer.invoke('reveal', p),
  defaultVideoDir: () => ipcRenderer.invoke('default-video-dir'),
  ytStatus: () => ipcRenderer.invoke('yt-status'),
  ytUpdate: () => ipcRenderer.invoke('yt-update'),
  ytDownload: (opts) => ipcRenderer.invoke('yt-download', opts),
  ffInstall: () => ipcRenderer.invoke('ff-install'),
  ytCancel: () => ipcRenderer.invoke('yt-cancel'),
  onYtProgress: (cb) => ipcRenderer.on('yt-progress', (_e, m) => cb(m)),
  defaultFramesDir: () => ipcRenderer.invoke('default-frames-dir'),
  pickVideo: () => ipcRenderer.invoke('pick-video'),
  framesStart: (opts) => ipcRenderer.invoke('frames-start', opts),
  framesCancel: () => ipcRenderer.invoke('frames-cancel'),
  onFramesProgress: (cb) => ipcRenderer.on('frames-progress', (_e, m) => cb(m)),
  defaultPitchDir: () => ipcRenderer.invoke('default-pitch-dir'),
  pitchSignIn: (url) => ipcRenderer.invoke('pitch-signin', url),
  pitchSignOut: () => ipcRenderer.invoke('pitch-signout'),
  pitchStatus: () => ipcRenderer.invoke('pitch-status'),
  pitchScan: (opts) => ipcRenderer.invoke('pitch-scan', opts),
  pitchDownload: (opts) => ipcRenderer.invoke('pitch-download', opts),
  pitchCancel: () => ipcRenderer.invoke('pitch-cancel'),
  onPitchProgress: (cb) => ipcRenderer.on('pitch-progress', (_e, m) => cb(m)),
  onProgress: (cb) => ipcRenderer.on('progress', (_e, m) => cb(m)),
});
